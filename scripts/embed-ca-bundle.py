#!/usr/bin/env python3
"""Turn a PEM CA bundle into a C string for the PS5 payload build."""
from pathlib import Path
import argparse

parser = argparse.ArgumentParser()
parser.add_argument("input", type=Path)
parser.add_argument("output", type=Path)
parser.add_argument("--extra", type=Path, action="append", default=[],
                    help="additional PEM trust anchor to append (repeatable)")
args = parser.parse_args()
source = args.input.read_text(encoding="ascii")
for extra_path in args.extra:
    extra = extra_path.read_text(encoding="ascii")
    if "-----BEGIN CERTIFICATE-----" not in extra or "-----END CERTIFICATE-----" not in extra:
        raise SystemExit(f"{extra_path} does not contain a PEM certificate")
    source += "\n" + extra.rstrip() + "\n"
certificate_count = source.count("-----BEGIN CERTIFICATE-----")
if not certificate_count or "-----END CERTIFICATE-----" not in source:
    raise SystemExit("input does not look like a PEM CA bundle")

lines = [
    "/* Generated by scripts/embed-ca-bundle.py; Mozilla-derived Debian CA bundle plus documented extras. */",
    "#ifndef RD_HOST_BUILD",
    f"#define RD_CA_BUNDLE_CERT_COUNT {certificate_count}U",
    "static const char rd_ca_bundle_pem[] =",
]
for line in source.splitlines():
    escaped = line.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    "{escaped}\\n"')
lines.extend(["    ;", "#endif", ""])
args.output.write_text("\n".join(lines), encoding="ascii")
